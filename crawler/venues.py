_CITY_HINTS = ["臺北市", "台北市", "新北市", "桃園市", "臺中市", "台中市",
               "臺南市", "台南市", "高雄市", "基隆市", "新竹市", "新竹縣"]


def lookup(venue: Optional[str]) -> tuple[Optional[str], Optional[str]]:
    """回傳 (縣市, 行政區)。查不到回 (None, None) —— 不要猜。"""
    if not venue:
        return None, None
    for key, (city, district) in VENUE_CITY.items():
        if key in venue:
            return city, district
    for hint in _CITY_HINTS:
        if hint in venue:
            return hint.replace("台", "臺"), None
    return None, None
